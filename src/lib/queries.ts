type SearchParamsInput = Record<string, string | string[] | undefined> | URLSearchParams;

function getParam(sp: SearchParamsInput, k: string): string | undefined {
  if (sp instanceof URLSearchParams) return sp.get(k) ?? undefined;
  const v = sp[k];
  return Array.isArray(v) ? v[0] : v;
}

export function parseFilters(sp: SearchParamsInput): LibraryFilters {
  const kind = getParam(sp, "kind");
  const orient = getParam(sp, "orient");
  const folder = getParam(sp, "folder");
  const sort = getParam(sp, "sort");
  const source = getParam(sp, "source");
  const clients = (getParam(sp, "clients") ?? "")
    .split(",")
    .map((s) => s.trim())
    .filter((s) => /^[a-z0-9]{2,32}$/.test(s));
  const cls = [...new Set((getParam(sp, "cls") ?? "").split(",").map((s) => s.trim()))].filter((c) =>
    (CATEGORY_IDS as string[]).includes(c),
  );
  const energy = getParam(sp, "energy");
  return {
    kind: kind === "video" || kind === "image" || kind === "audio" ? kind : null,
    orient: ORIENTATIONS.includes(orient as Orientation) ? (orient as Orientation) : null,
    folder: folder && /^r\d+(\/.{1,300})?$/.test(folder) ? folder : null,
    clients,
    shared: getParam(sp, "shared") !== "0",
    source: SOURCES.includes(source as SourceKey) ? (source as SourceKey) : "all",
    cls,
    review: getParam(sp, "review") === "1",
    energy: ENERGY_BUCKET_IDS.includes(energy as EnergyBucket) ? (energy as EnergyBucket) : null,
    sort: SORTS.includes(sort as SortKey) ? (sort as SortKey) : "newest",
    q: (getParam(sp, "q") ?? "").slice(0, 200).trim(),
    meaning: getParam(sp, "mode") === "meaning",
    page: parsePage(getParam(sp, "page")),
  };
}

/** Rows the UI shows: file present and not soft-hidden by an ignore pattern. */
const VISIBLE = "a.missing = 0 and a.ignored = 0";

/** Escape backslash, % and _ for a `like ? escape` pattern (the one copy; the Hooks tab text filter reuses it). */
export const likeEscape = (s: string) => s.replace(/[\\%_]/g, (m) => "\\" + m);

/**
 * One search term as an FTS5 query over the description + spoken opening columns: always a quoted string with a
 * prefix star (`{description spoken_open} : "kitch"*`), never raw user syntax. Quotes are dropped; a term with no
 * letter or digit gets no FTS part (it can still match the filename / path).
 */
export function ftsTerm(term: string): string | null {
  const clean = term.replace(/"/g, " ").replace(/\s+/g, " ").trim().slice(0, 100);
  if (!/[\p{L}\p{N}]/u.test(clean)) return null;
  return `{description spoken_open} : "${clean}"*`;
}

export type Where = { sql: string; params: unknown[] };

function buildWhere(
  scope: Scope,
  f: LibraryFilters,
  opts: {
    skipFolder?: boolean;
    skipKind?: boolean;
    skipOrient?: boolean;
    skipSource?: boolean;
    skipClass?: boolean;
    skipReview?: boolean;
    skipEnergy?: boolean;
  } = {},
): Where {
  const w: string[] = ["r.enabled = 1", VISIBLE];
  const p: unknown[] = [];
  if (scope.kind === "rtm" || scope.kind === "fkbpros" || scope.kind === "fkb") {
    w.push("s.key = ?");
    p.push(scope.kind);
  } else if (scope.kind === "client") {
    w.push("s.key = 'fkbpros'");
    const tagged = "exists (select 1 from asset_clients ac join clients c on c.id = ac.client_id where ac.asset_id = a.id and c.code = ?)";
    if (f.shared) {
      w.push(`(${tagged} or not exists (select 1 from asset_clients ac2 where ac2.asset_id = a.id))`);
    } else {
      w.push(tagged);
    }
    p.push(scope.code);
  }
  if (scope.kind === "fkbpros" && f.clients.length) {
    const codes = f.clients.filter((c) => c !== "shared");
    const parts: string[] = [];
    if (codes.length) {
      parts.push(
        `exists (select 1 from asset_clients ac join clients c on c.id = ac.client_id where ac.asset_id = a.id and c.code in (${codes.map(() => "?").join(",")}))`,
      );
      p.push(...codes);
    }
    if (f.clients.includes("shared")) parts.push("not exists (select 1 from asset_clients ac2 where ac2.asset_id = a.id)");
    if (parts.length) w.push(`(${parts.join(" or ")})`);
  }
  if (f.kind && !opts.skipKind) {
    w.push("a.kind = ?");
    p.push(f.kind);
  }
  if (f.source !== "all" && !opts.skipSource) w.push(f.source === "generated" ? "a.generated = 1" : "a.generated = 0");
  if (f.cls.length && !opts.skipClass) {
    w.push(`a.asset_class in (${f.cls.map(() => "?").join(",")})`);
    p.push(...f.cls);
  }
  if (f.review && !opts.skipReview) w.push("a.needs_review = 1");
  if (f.energy && !opts.skipEnergy) {
    const b = ENERGY_BUCKETS[f.energy];
    w.push("a.energy >= ? and a.energy < ?");
    p.push(b.min, b.max);
  }
  if (f.orient && !opts.skipOrient) {
    w.push("a.orientation = ?");
    p.push(f.orient);
  }
  if (f.folder && !opts.skipFolder) {
    const m = /^r(\d+)(?:\/(.+))?$/.exec(f.folder);
    if (m) {
      w.push("a.root_id = ?");
      p.push(Number(m[1]));
      if (m[2]) {
        w.push("a.rel_path like ? escape '\\'");
        p.push(likeEscape(m[2]) + "/%");
      }
    }
  }
  if (f.q) {
    // Every term must match the filename or path (substring, as before) or the description / spoken opening (FTS5).
    for (const term of f.q.split(/\s+/).filter(Boolean).slice(0, 6)) {
      const t = `%${likeEscape(term)}%`;
      const fts = ftsTerm(term);
      if (fts) {
        w.push("(a.filename like ? escape '\\' or a.rel_path like ? escape '\\' or a.id in (select rowid from asset_fts where asset_fts match ?))");
        p.push(t, t, fts);
      } else {
        w.push("(a.filename like ? escape '\\' or a.rel_path like ? escape '\\')");
        p.push(t, t);
      }
    }
  }
  return { sql: w.join(" and "), params: p };
}

