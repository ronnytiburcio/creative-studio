export function readTail(file: string | null, lines = 14): string[] {
  if (!file) return [];
  const safe = resolveInside(file, [getConfig().logsDir]);
  if (!safe) return [];
  try {
    const fd = fs.openSync(safe, "r");
    try {
      const size = fs.fstatSync(fd).size;
      const len = Math.min(size, 6000);
      const buf = Buffer.alloc(len);
      fs.readSync(fd, buf, 0, len, size - len);
      return buf.toString("utf8").split("\n").filter(Boolean).slice(-lines);
    } finally {
      fs.closeSync(fd);
    }
  } catch {
    return [];
  }
}

