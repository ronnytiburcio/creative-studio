function reviewWhere(scope: ReviewScope): Where {
  // A switched-off lane's files leave Review too (their answers stay; they come back with the lane).
  const w = ["r.enabled = 1", "s.enabled = 1", VISIBLE, "a.kind in ('image','video')", "a.needs_review = 1"];
  const p: unknown[] = [];
  if (scope.kind === "rtm" || scope.kind === "fkbpros" || scope.kind === "fkb") {
    w.push("s.key = ?");
    p.push(scope.kind);
  } else if (scope.kind === "client") {
    w.push(
      `(exists (select 1 from asset_clients ac join clients c on c.id = ac.client_id where ac.asset_id = a.id and c.code = ?)
        or exists (select 1 from classifications k where k.asset_id = a.id
                     and cast(json_extract(k.answers, '$.' || ? || '.value') as real) >= 0.5))`,
    );
    p.push(scope.code, `client_${scope.code}`);
  }
  return { sql: w.join(" and "), params: p };
}

/** Asset ids waiting in Review (oldest classified first, so the queue reads in the order Jev filed them). */
export function reviewQueue(scope: ReviewScope, limit = 2000): number[] {
  const where = reviewWhere(scope);
  return getDb()
    .sqlite.prepare(`select a.id ${FROM} where ${where.sql} order by a.classified_at, a.id limit ?`)
    .pluck()
    .all(...where.params, limit) as number[];
}

