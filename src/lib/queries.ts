const CARD_COLS =
  "a.id, a.filename, a.rel_path, r.path as root_path, s.key as section_key, a.kind, a.ext, a.duration_s, a.width, a.height, a.orientation, a.bytes, a.mtime, a.sha256, a.thumb_path, a.sheet_path, a.proxy_path, a.derive_status, a.generated, a.asset_class, a.needs_review";

function clientChips(ids: number[]): Map<number, ClientChip[]> {
  const out = new Map<number, ClientChip[]>();
  if (!ids.length) return out;
  const rows = getDb()
    .sqlite.prepare(
      `select ac.asset_id, c.code, c.name, ac.source from asset_clients ac join clients c on c.id = ac.client_id
        where ac.asset_id in (${ids.map(() => "?").join(",")}) order by c.sort`,
    )
    .all(...ids) as { asset_id: number; code: string; name: string; source: string }[];
  for (const r of rows) {
    const list = out.get(r.asset_id) ?? [];
    list.push({ code: r.code, short: clientShortName(r.name), source: r.source });
    out.set(r.asset_id, list);
  }
  return out;
}

function toCard(r: Row, chips: Map<number, ClientChip[]>): AssetCard {
  const dir = path.posix.dirname(r.rel_path);
  return {
    id: r.id,
    filename: r.filename,
    relDir: dir === "." ? "" : dir,
    rootLabel: path.basename(r.root_path),
    sectionKey: r.section_key,
    kind: r.kind,
    ext: r.ext,
    durationS: r.duration_s,
    width: r.width,
    height: r.height,
    orientation: r.orientation,
    bytes: r.bytes,
    mtime: r.mtime,
    v: (r.sha256 ?? "").slice(0, 12),
    hasThumb: Boolean(r.thumb_path),
    hasSheet: Boolean(r.sheet_path),
    hasProxy: Boolean(r.proxy_path),
    deriveStatus: r.derive_status,
    generated: Boolean(r.generated),
    proof: isProofPath(path.join(r.root_path, r.rel_path)),
    clients: chips.get(r.id) ?? [],
    assetClass: r.asset_class,
    needsReview: r.needs_review === 1,
  };
}

/** Library cards a page (the Library pages by `page` since 2026-10-06; /api/assets takes its own `limit` too). */
export const PAGE_SIZE = LIST_PAGE_SIZE;

export function listAssets(scope: Scope, f: LibraryFilters, offset = 0, limit = PAGE_SIZE) {
  const { sqlite } = getDb();
  const where = buildWhere(scope, f);
  const total = (sqlite.prepare(`select count(*) as n ${FROM} where ${where.sql}`).get(...where.params) as { n: number }).n;
  const rows = sqlite
    .prepare(`select ${CARD_COLS} ${FROM} where ${where.sql} order by ${ORDER[f.sort]} limit ? offset ?`)
    .all(...where.params, Math.min(Math.max(limit, 1), 200), Math.max(offset, 0)) as Row[];
  const chips = clientChips(rows.map((r) => r.id));
  return { total, items: rows.map((r) => toCard(r, chips)) };
}

/** Cards for these ids (visible files only), in the order given. */
export function cardsByIds(ids: number[]): AssetCard[] {
  const unique = [...new Set(ids)].slice(0, 1000);
  if (!unique.length) return [];
  const rows = getDb()
    .sqlite.prepare(`select ${CARD_COLS} ${FROM} where r.enabled = 1 and ${VISIBLE} and a.id in (${unique.map(() => "?").join(",")})`)
    .all(...unique) as Row[];
  const chips = clientChips(rows.map((r) => r.id));
  const byId = new Map(rows.map((r) => [r.id, toCard(r, chips)]));
  return unique.map((id) => byId.get(id)).filter((c): c is AssetCard => Boolean(c));
}

/** A root (depth 0) or a folder prefix under it (depth 1..3). `path` is the root-relative prefix. */
export type FolderOption = { value: string; label: string; path: string; count: number; depth: 0 | 1 | 2 | 3 };

export const FOLDER_DEPTH = 3;

export function filterOptions(scope: Scope, f: LibraryFilters) {
  const { sqlite } = getDb();
  const folderWhere = buildWhere(scope, f, { skipFolder: true });
  const folderRows = sqlite
    .prepare(
      `select a.root_id, r.path as root_path, a.rel_path, count(*) as n
         ${FROM} where ${folderWhere.sql} group by a.root_id, a.rel_path`,
    )
    .all(...folderWhere.params) as { root_id: number; root_path: string; rel_path: string; n: number }[];
  // Count every folder prefix up to FOLDER_DEPTH levels deep, per root.
  const roots = new Map<number, { label: string; count: number; prefixes: Map<string, number> }>();
  for (const row of folderRows) {
    const root = roots.get(row.root_id) ?? { label: path.basename(row.root_path), count: 0, prefixes: new Map() };
    root.count += row.n;
    const dirs = row.rel_path.split("/").slice(0, -1);
    for (let depth = 1; depth <= Math.min(FOLDER_DEPTH, dirs.length); depth++) {
      const prefix = dirs.slice(0, depth).join("/");
      root.prefixes.set(prefix, (root.prefixes.get(prefix) ?? 0) + row.n);
    }
    roots.set(row.root_id, root);
  }
  const folders: FolderOption[] = [];
  const byName = (a: string, b: string) => a.localeCompare(b, undefined, { sensitivity: "base", numeric: true });
  for (const [rootId, root] of [...roots].sort((a, b) => byName(a[1].label, b[1].label))) {
    folders.push({ value: `r${rootId}`, label: root.label, path: "", count: root.count, depth: 0 });
    // Sorting segment-wise keeps children directly under their parent.
    const prefixes = [...root.prefixes].sort(([a], [b]) => {
      const sa = a.split("/");
      const sb = b.split("/");
      for (let i = 0; i < Math.min(sa.length, sb.length); i++) {
        const cmp = byName(sa[i], sb[i]);
        if (cmp) return cmp;
      }
      return sa.length - sb.length;
    });
    for (const [prefix, count] of prefixes) {
      const segments = prefix.split("/");
      folders.push({
        value: `r${rootId}/${prefix}`,
        label: segments[segments.length - 1],
        path: prefix,
        count,
        depth: segments.length as 1 | 2 | 3,
      });
    }
  }

  const kindWhere = buildWhere(scope, f, { skipKind: true });
  const kinds = sqlite
    .prepare(`select a.kind as k, count(*) as n ${FROM} where ${kindWhere.sql} group by a.kind`)
    .all(...kindWhere.params) as { k: string; n: number }[];
  const orientWhere = buildWhere(scope, f, { skipOrient: true });
  const orients = sqlite
    .prepare(`select coalesce(a.orientation, 'other') as k, count(*) as n ${FROM} where ${orientWhere.sql} group by 1`)
    .all(...orientWhere.params) as { k: string; n: number }[];
  const sourceWhere = buildWhere(scope, f, { skipSource: true });
  const sources = sqlite
    .prepare(`select a.generated as g, count(*) as n ${FROM} where ${sourceWhere.sql} group by a.generated`)
    .all(...sourceWhere.params) as { g: number; n: number }[];
  const generated = sources.find((row) => row.g === 1)?.n ?? 0;
  const originals = sources.find((row) => row.g === 0)?.n ?? 0;
  const classWhere = buildWhere(scope, f, { skipClass: true });
  const classes = sqlite
    .prepare(`select a.asset_class as k, count(*) as n ${FROM} where ${classWhere.sql} and a.asset_class is not null group by a.asset_class`)
    .all(...classWhere.params) as { k: string; n: number }[];
  const reviewWhere = buildWhere(scope, f, { skipReview: true });
  const review = (
    sqlite.prepare(`select count(*) as n ${FROM} where ${reviewWhere.sql} and a.needs_review = 1`).get(...reviewWhere.params) as { n: number }
  ).n;
  const energyWhere = buildWhere(scope, f, { skipEnergy: true });
  const energyRows = sqlite
    .prepare(
      `select case when a.energy < 2.5 then 'low' when a.energy < 3.5 then 'mid' else 'high' end as k, count(*) as n
         ${FROM} where ${energyWhere.sql} and a.energy is not null group by 1`,
    )
    .all(...energyWhere.params) as { k: string; n: number }[];
  return {
    folders,
    kinds: Object.fromEntries(kinds.map((row) => [row.k, row.n])) as Record<string, number>,
    orients: Object.fromEntries(orients.map((row) => [row.k, row.n])) as Record<string, number>,
    sources: { all: generated + originals, generated, originals } as Record<SourceKey, number>,
    classes: Object.fromEntries(classes.map((row) => [row.k, row.n])) as Record<string, number>,
    review,
    energies: Object.fromEntries(energyRows.map((row) => [row.k, row.n])) as Record<string, number>,
  };
}

export type ClientRow = {
  id: number;
  code: string;
  name: string;
  short: string;
  metaAdAccountId: string | null;
  count: number;
};

/**
 * Clients in sidebar order. Hidden clients (Settings > Clients, Creative Studio 1b) are left out unless asked for: the
 * sidebar, channel routes, cmd+K, Review, pickers and every list built on this skip them; their rows stay.
 */
export function listClients(opts: { includeHidden?: boolean } = {}): ClientRow[] {
  const rows = getDb()
    .sqlite.prepare(
      `select c.id, c.code, c.name, c.meta_ad_account_id,
              (select count(*) from asset_clients ac join assets a on a.id = ac.asset_id join roots r on r.id = a.root_id
                 where ac.client_id = c.id and ${VISIBLE} and r.enabled = 1) as n
         from clients c ${opts.includeHidden ? "" : "where c.hidden_at is null"} order by c.sort, c.name`,
    )
    .all() as { id: number; code: string; name: string; meta_ad_account_id: string | null; n: number }[];
  return rows.map((r) => ({
    id: r.id,
    code: r.code,
    name: r.name,
    short: clientShortName(r.name),
    metaAdAccountId: r.meta_ad_account_id,
    count: r.n,
  }));
}

export function getClient(code: string): ClientRow | undefined {
  return listClients().find((c) => c.code === code);
}

/** The sidebar: enabled lanes (name, color, file count; a switched-off lane is left out), visible clients, shared count. */
export function sidebarData() {
  const { sqlite } = getDb();
  const sections = sqlite
    .prepare(
      `select s.key, s.name, s.color, (select count(*) from assets a join roots r on r.id = a.root_id
          where a.section_id = s.id and ${VISIBLE} and r.enabled = 1) as n
         from sections s where s.enabled = 1 order by s.sort`,
    )
    .all() as { key: string; name: string; color: string | null; n: number }[];
  const sharedCount = (
    sqlite
      .prepare(
        `select count(*) as n from assets a join roots r on r.id = a.root_id join sections s on s.id = a.section_id
          where s.key = 'fkbpros' and ${VISIBLE} and r.enabled = 1
            and not exists (select 1 from asset_clients ac where ac.asset_id = a.id)`,
      )
      .get() as { n: number }
  ).n;
  return {
    sections: sections.map((s) => ({ key: s.key, name: s.name, color: s.color, count: s.n })),
    clients: listClients().map(({ code, name, short, count }) => ({ code, name, short, count })),
    sharedCount,
  };
}

